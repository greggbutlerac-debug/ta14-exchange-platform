export const TA14_REGISTRY_PUBLICATION_BOUNDARY =
  "Registry Publication preserves approved records. Publication is not execution.";

export type PublicationState =
  | "draft"
  | "ready"
  | "published"
  | "superseded"
  | "withdrawn";

export interface RegistryPublicationRecord {
  publicationId: string;
  reviewId: string;
  determinationId: string;
  state: PublicationState;
  registryIdentifier: string;
  publicationHash: string;
  publishedAt?: string;
  createdExecutionArtifact: false;
  createdExecution: false;
}

export function validatePublication(
  value: RegistryPublicationRecord,
): void {
  if (value.createdExecutionArtifact !== false)
    throw new Error("Publication cannot create execution artifacts.");
  if (value.createdExecution !== false)
    throw new Error("Publication cannot execute actions.");
}

export default {
  boundary: TA14_REGISTRY_PUBLICATION_BOUNDARY,
  validatePublication,
};
