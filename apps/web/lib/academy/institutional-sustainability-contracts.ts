export const TA14_INSTITUTIONAL_SUSTAINABILITY_BOUNDARY =
  "Institutional sustainability preserves mission, governance, and evidence without rewriting history.";

export type InstitutionalSustainabilityState =
  | "planned"
  | "operational"
  | "measured"
  | "improving"
  | "sustained";

export interface InstitutionalSustainabilityRecord {
  sustainabilityId: string;
  resilienceId: string;
  state: InstitutionalSustainabilityState;
  preservesHistory: true;
  rewritesHistory: false;
  integrityHash: string;
}

export function validateInstitutionalSustainability(
  value: InstitutionalSustainabilityRecord,
): void {
  if (!value.preservesHistory) {
    throw new Error("Institutional sustainability must preserve history.");
  }
  if (value.rewritesHistory) {
    throw new Error("Institutional sustainability cannot rewrite history.");
  }
}

export default {
  boundary: TA14_INSTITUTIONAL_SUSTAINABILITY_BOUNDARY,
  validateInstitutionalSustainability,
};
