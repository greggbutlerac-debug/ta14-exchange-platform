export const TA14_OUTCOME_BOUNDARY =
  "Outcomes preserve reality after execution. They do not rewrite governance.";

export type OutcomeState =
  | "observed"
  | "verified"
  | "partially_verified"
  | "disputed"
  | "failed"
  | "closed";

export interface OutcomeRecord {
  outcomeId: string;
  executionId: string;
  artifactId: string;
  determinationId: string;
  state: OutcomeState;
  observedAt: string;
  outcomeHash: string;
  modifiesExecution: false;
  modifiesArtifact: false;
  modifiesPublication: false;
  modifiesReview: false;
  modifiesDetermination: false;
}

export function validateOutcome(record: OutcomeRecord): void {
  if (
    record.modifiesExecution ||
    record.modifiesArtifact ||
    record.modifiesPublication ||
    record.modifiesReview ||
    record.modifiesDetermination
  ) {
    throw new Error("Outcome records cannot modify upstream governance.");
  }
}

export default {
  boundary: TA14_OUTCOME_BOUNDARY,
  validateOutcome,
};
