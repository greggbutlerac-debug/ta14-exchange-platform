export const TA14_INSTITUTIONAL_STRATEGY_BOUNDARY =
  "Strategy guides future direction while preserving immutable governance history.";

export type InstitutionalStrategyState =
  | "proposed"
  | "approved"
  | "active"
  | "reviewed"
  | "retired";

export interface InstitutionalStrategyRecord {
  strategyId: string;
  intelligenceId: string;
  state: InstitutionalStrategyState;
  preservesHistory: true;
  rewritesHistory: false;
  integrityHash: string;
}

export function validateInstitutionalStrategy(
  value: InstitutionalStrategyRecord,
): void {
  if (!value.preservesHistory) {
    throw new Error("Institutional strategy must preserve history.");
  }
  if (value.rewritesHistory) {
    throw new Error("Institutional strategy cannot rewrite history.");
  }
}

export default {
  boundary: TA14_INSTITUTIONAL_STRATEGY_BOUNDARY,
  validateInstitutionalStrategy,
};
