export const TA14_EXECUTION_ARTIFACT_BOUNDARY =
  "Execution Artifacts preserve attributable execution evidence. They are not execution.";

export type ExecutionArtifactState =
  | "draft"
  | "assembled"
  | "sealed"
  | "registered"
  | "superseded"
  | "withdrawn";

export interface ExecutionArtifactRecord {
  artifactId: string;
  publicationId: string;
  determinationId: string;
  state: ExecutionArtifactState;
  artifactHash: string;
  sealedAt?: string;
  executed: false;
}

export function validateExecutionArtifact(
  value: ExecutionArtifactRecord,
): void {
  if (value.executed !== false) {
    throw new Error("Execution artifacts cannot perform execution.");
  }
}

