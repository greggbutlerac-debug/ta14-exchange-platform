export const TA14_INSTITUTIONAL_EVOLUTION_BOUNDARY =
  "Institutional evolution creates new versions without rewriting prior governance.";

export type InstitutionalEvolutionState =
  | "proposed"
  | "under_review"
  | "approved"
  | "active"
  | "superseded";

export interface InstitutionalEvolutionRecord {
  evolutionId: string;
  previousVersionId?: string;
  nextVersionId?: string;
  state: InstitutionalEvolutionState;
  preservesHistory: true;
  rewritesHistory: false;
  integrityHash: string;
}

export function validateInstitutionalEvolution(
  value: InstitutionalEvolutionRecord,
): void {
  if (!value.preservesHistory) {
    throw new Error("Institutional evolution must preserve history.");
  }
  if (value.rewritesHistory) {
    throw new Error("Institutional evolution cannot rewrite history.");
  }
}

export default {
  boundary: TA14_INSTITUTIONAL_EVOLUTION_BOUNDARY,
  validateInstitutionalEvolution,
};
