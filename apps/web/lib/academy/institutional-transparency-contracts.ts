export const TA14_INSTITUTIONAL_TRANSPARENCY_BOUNDARY =
  "Transparency makes governance inspectable without exposing protected information or rewriting history.";

export type InstitutionalTransparencyState =
  | "draft"
  | "reviewed"
  | "approved"
  | "published"
  | "archived";

export interface InstitutionalTransparencyRecord {
  transparencyId: string;
  accountabilityId: string;
  publicationScope: "private" | "restricted" | "public";
  state: InstitutionalTransparencyState;
  preservesHistory: true;
  rewritesHistory: false;
  integrityHash: string;
}

export function validateInstitutionalTransparency(
  value: InstitutionalTransparencyRecord,
): void {
  if (!value.preservesHistory) {
    throw new Error("Institutional transparency must preserve history.");
  }
  if (value.rewritesHistory) {
    throw new Error("Institutional transparency cannot rewrite history.");
  }
}

export default {
  boundary: TA14_INSTITUTIONAL_TRANSPARENCY_BOUNDARY,
  validateInstitutionalTransparency,
};
