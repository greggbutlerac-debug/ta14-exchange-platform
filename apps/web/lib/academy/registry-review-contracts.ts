export const TA14_REGISTRY_REVIEW_BOUNDARY =
  "Registry Review evaluates a committed determination for registration eligibility. It does not create publication, execution artifacts, or execution.";

export const REVIEW_OUTCOMES = [
  "accept_for_registration",
  "return_for_correction",
  "hold",
  "escalate",
  "reject",
] as const;

export type ReviewOutcome = typeof REVIEW_OUTCOMES[number];

export interface RegistryReviewRecord {
  reviewId: string;
  determinationId: string;
  reviewerId: string;
  outcome: ReviewOutcome;
  rationale: string;
  conditions: readonly string[];
  limitations: readonly string[];
  committedDeterminationHash: string;
  reviewHash: string;
  createdAt: string;
  createdPublication: false;
  createdExecutionArtifact: false;
  createdExecution: false;
}

export function validateRegistryReview(
  review: RegistryReviewRecord,
): void {
  if (!REVIEW_OUTCOMES.includes(review.outcome)) {
    throw new Error("Invalid registry review outcome.");
  }

  if (review.createdPublication !== false)
    throw new Error("Registry review cannot publish.");

  if (review.createdExecutionArtifact !== false)
    throw new Error("Registry review cannot create artifacts.");

  if (review.createdExecution !== false)
    throw new Error("Registry review cannot execute.");
}

export default {
  boundary: TA14_REGISTRY_REVIEW_BOUNDARY,
  validateRegistryReview,
};
