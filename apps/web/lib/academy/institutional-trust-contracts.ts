export type InstitutionalTrustState =
  | "developing"
  | "established"
  | "maintained"
  | "challenged"
  | "restored";

export interface InstitutionalTrustRecord {
  trustId: string;
  transparencyId: string;
  state: InstitutionalTrustState;
  preservesHistory: true;
  rewritesHistory: false;
  integrityHash: string;
}

export function validateInstitutionalTrust(
  value: InstitutionalTrustRecord,
): void {
  if (!value.preservesHistory) throw new Error("Institutional trust must preserve history.");
  if (value.rewritesHistory) throw new Error("Institutional trust cannot rewrite history.");
}

