export const TA14_INSTITUTIONAL_ACCOUNTABILITY_BOUNDARY =
  "Accountability assigns responsibility without altering historical records.";

export type InstitutionalAccountabilityState =
  | "assigned"
  | "accepted"
  | "active"
  | "fulfilled"
  | "closed";

export interface InstitutionalAccountabilityRecord {
  accountabilityId: string;
  oversightId: string;
  responsibleSubjectId: string;
  state: InstitutionalAccountabilityState;
  preservesHistory: true;
  rewritesHistory: false;
  integrityHash: string;
}

export function validateInstitutionalAccountability(
  value: InstitutionalAccountabilityRecord,
): void {
  if (!value.preservesHistory) {
    throw new Error("Institutional accountability must preserve history.");
  }
  if (value.rewritesHistory) {
    throw new Error("Institutional accountability cannot rewrite history.");
  }
}

export default {
  boundary: TA14_INSTITUTIONAL_ACCOUNTABILITY_BOUNDARY,
  validateInstitutionalAccountability,
};
