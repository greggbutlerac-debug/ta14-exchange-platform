export const TA14_INSTITUTIONAL_ASSURANCE_BOUNDARY =
  "Assurance evaluates institutional integrity without rewriting history.";

export type InstitutionalAssuranceState =
  | "scheduled"
  | "in_review"
  | "verified"
  | "follow_up_required"
  | "closed";

export interface InstitutionalAssuranceRecord {
  assuranceId: string;
  stewardshipId: string;
  state: InstitutionalAssuranceState;
  preservesHistory: true;
  rewritesHistory: false;
  integrityHash: string;
}

export function validateInstitutionalAssurance(
  value: InstitutionalAssuranceRecord,
): void {
  if (!value.preservesHistory) {
    throw new Error("Institutional assurance must preserve history.");
  }
  if (value.rewritesHistory) {
    throw new Error("Institutional assurance cannot rewrite history.");
  }
}

