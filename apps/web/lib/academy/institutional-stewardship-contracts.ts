export const TA14_INSTITUTIONAL_STEWARDSHIP_BOUNDARY =
  "Stewardship maintains the institution without rewriting its history.";

export type InstitutionalStewardshipState =
  | "assigned"
  | "active"
  | "reviewing"
  | "completed"
  | "transitioned";

export interface InstitutionalStewardshipRecord {
  stewardshipId: string;
  strategyId: string;
  state: InstitutionalStewardshipState;
  preservesHistory: true;
  rewritesHistory: false;
  integrityHash: string;
}

export function validateInstitutionalStewardship(
  value: InstitutionalStewardshipRecord,
): void {
  if (!value.preservesHistory) {
    throw new Error("Institutional stewardship must preserve history.");
  }
  if (value.rewritesHistory) {
    throw new Error("Institutional stewardship cannot rewrite history.");
  }
}

