export const TA14_INSTITUTIONAL_INTELLIGENCE_BOUNDARY =
  "Institutional intelligence recommends; it never rewrites history.";

export type InstitutionalIntelligenceState =
  | "collecting"
  | "analyzing"
  | "recommended"
  | "implemented"
  | "retired";

export interface InstitutionalIntelligenceRecord {
  intelligenceId: string;
  knowledgeId: string;
  state: InstitutionalIntelligenceState;
  preservesHistory: true;
  rewritesHistory: false;
  integrityHash: string;
}

export function validateInstitutionalIntelligence(
  value: InstitutionalIntelligenceRecord,
): void {
  if (!value.preservesHistory) {
    throw new Error("Institutional intelligence must preserve history.");
  }
  if (value.rewritesHistory) {
    throw new Error("Institutional intelligence cannot rewrite history.");
  }
}

export default {
  boundary: TA14_INSTITUTIONAL_INTELLIGENCE_BOUNDARY,
  validateInstitutionalIntelligence,
};
