export const TA14_INSTITUTIONAL_MEMORY_BOUNDARY =
  "Institutional memory extends knowledge while preserving immutable history.";

export type InstitutionalMemoryState =
  | "active"
  | "archived"
  | "historical";

export interface InstitutionalMemoryRecord {
  memoryId: string;
  sourceRecordId: string;
  lineageId: string;
  state: InstitutionalMemoryState;
  preservesHistory: true;
  rewritesHistory: false;
  integrityHash: string;
}

export function validateInstitutionalMemory(
  value: InstitutionalMemoryRecord,
): void {
  if (!value.preservesHistory) {
    throw new Error("Institutional memory must preserve history.");
  }
  if (value.rewritesHistory) {
    throw new Error("Institutional memory cannot rewrite history.");
  }
}

export default {
  boundary: TA14_INSTITUTIONAL_MEMORY_BOUNDARY,
  validateInstitutionalMemory,
};
