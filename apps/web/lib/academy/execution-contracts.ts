export const TA14_EXECUTION_BOUNDARY =
  "Execution performs only authorized actions from admissible execution artifacts.";

export type ExecutionState =
  | "pending"
  | "authorized"
  | "executing"
  | "completed"
  | "failed"
  | "rolled_back"
  | "cancelled";

export interface ExecutionRecord {
  executionId: string;
  artifactId: string;
  determinationId: string;
  state: ExecutionState;
  startedAt?: string;
  completedAt?: string;
  executionHash: string;
  modifiesArtifact: false;
  modifiesPublication: false;
  modifiesReview: false;
  modifiesDetermination: false;
}

export function validateExecution(record: ExecutionRecord): void {
  if (
    record.modifiesArtifact ||
    record.modifiesPublication ||
    record.modifiesReview ||
    record.modifiesDetermination
  ) {
    throw new Error("Execution cannot mutate upstream governance records.");
  }
}

export default {
  boundary: TA14_EXECUTION_BOUNDARY,
  validateExecution,
};
