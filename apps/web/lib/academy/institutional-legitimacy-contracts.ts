export const TA14_INSTITUTIONAL_LEGITIMACY_BOUNDARY =
  "Institutional legitimacy is demonstrated through governed evidence and accountable operation, never asserted by declaration.";

export type InstitutionalLegitimacyState =
  | "emerging"
  | "recognized"
  | "maintained"
  | "challenged"
  | "renewed";

export interface InstitutionalLegitimacyRecord {
  legitimacyId: string;
  trustId: string;
  state: InstitutionalLegitimacyState;
  preservesHistory: true;
  rewritesHistory: false;
  integrityHash: string;
}

export function validateInstitutionalLegitimacy(
  value: InstitutionalLegitimacyRecord,
): void {
  if (!value.preservesHistory) {
    throw new Error("Institutional legitimacy must preserve history.");
  }
  if (value.rewritesHistory) {
    throw new Error("Institutional legitimacy cannot rewrite history.");
  }
}

export default {
  boundary: TA14_INSTITUTIONAL_LEGITIMACY_BOUNDARY,
  validateInstitutionalLegitimacy,
};
