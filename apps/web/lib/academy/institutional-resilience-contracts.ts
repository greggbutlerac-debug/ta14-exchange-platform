export const TA14_INSTITUTIONAL_RESILIENCE_BOUNDARY =
  "Institutional resilience preserves governed operation through disruption without rewriting history.";

export type InstitutionalResilienceState =
  | "prepared"
  | "monitoring"
  | "responding"
  | "recovering"
  | "restored";

export interface InstitutionalResilienceRecord {
  resilienceId: string;
  continuityGovernanceId: string;
  state: InstitutionalResilienceState;
  preservesHistory: true;
  rewritesHistory: false;
  integrityHash: string;
}

export function validateInstitutionalResilience(
  value: InstitutionalResilienceRecord,
): void {
  if (!value.preservesHistory) {
    throw new Error("Institutional resilience must preserve history.");
  }
  if (value.rewritesHistory) {
    throw new Error("Institutional resilience cannot rewrite history.");
  }
}

export default {
  boundary: TA14_INSTITUTIONAL_RESILIENCE_BOUNDARY,
  validateInstitutionalResilience,
};
