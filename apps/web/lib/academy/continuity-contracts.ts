export const TA14_CONTINUITY_BOUNDARY =
  "Continuity carries governed history forward without modifying prior records.";

export type ContinuityState =
  | "current"
  | "revalidation_required"
  | "superseded"
  | "archived";

export interface ContinuityRecord {
  continuityId: string;
  outcomeId: string;
  priorDeterminationId: string;
  state: ContinuityState;
  continuityHash: string;
  createdAt: string;
  modifiesOutcome: false;
  modifiesExecution: false;
  modifiesArtifact: false;
  modifiesPublication: false;
  modifiesReview: false;
  modifiesDetermination: false;
}

export function validateContinuity(record: ContinuityRecord): void {
  if (
    record.modifiesOutcome ||
    record.modifiesExecution ||
    record.modifiesArtifact ||
    record.modifiesPublication ||
    record.modifiesReview ||
    record.modifiesDetermination
  ) {
    throw new Error("Continuity cannot modify historical governance records.");
  }
}

export default {
  boundary: TA14_CONTINUITY_BOUNDARY,
  validateContinuity,
};
