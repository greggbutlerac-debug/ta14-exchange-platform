export const TA14_INSTITUTIONAL_KNOWLEDGE_BOUNDARY =
  "Knowledge is derived from immutable history and never rewrites it.";

export type InstitutionalKnowledgeState =
  | "draft"
  | "validated"
  | "published"
  | "superseded";

export interface InstitutionalKnowledgeRecord {
  knowledgeId: string;
  memoryId: string;
  version: string;
  state: InstitutionalKnowledgeState;
  preservesHistory: true;
  rewritesHistory: false;
  integrityHash: string;
}

export function validateInstitutionalKnowledge(
  value: InstitutionalKnowledgeRecord,
): void {
  if (!value.preservesHistory) throw new Error("History must be preserved.");
  if (value.rewritesHistory) throw new Error("Knowledge cannot rewrite history.");
}

export default {
  boundary: TA14_INSTITUTIONAL_KNOWLEDGE_BOUNDARY,
  validateInstitutionalKnowledge,
};
