export const TA14_GOVERNANCE_CYCLE_BOUNDARY =
  "Each governance cycle creates new records while preserving all prior cycles.";

export type GovernanceCycleState =
  | "initialized"
  | "active"
  | "revalidation_required"
  | "completed"
  | "superseded";

export interface GovernanceCycleRecord {
  cycleId: string;
  continuityId: string;
  priorCycleId?: string;
  state: GovernanceCycleState;
  cycleHash: string;
  preservesHistory: true;
  mutatesPriorCycle: false;
}

export function validateGovernanceCycle(
  value: GovernanceCycleRecord,
): void {
  if (!value.preservesHistory) {
    throw new Error("Governance cycles must preserve history.");
  }
  if (value.mutatesPriorCycle) {
    throw new Error("Governance cycles cannot rewrite previous cycles.");
  }
}

export default {
  boundary: TA14_GOVERNANCE_CYCLE_BOUNDARY,
  validateGovernanceCycle,
};
