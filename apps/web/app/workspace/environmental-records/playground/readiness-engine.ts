export type ReadinessState = 'NOT_YET_GOVERNED' | 'PARTIALLY_GOVERNABLE' | 'READY_FOR_ADMISSIBILITY_REVIEW' | 'ADMISSIBLE_FOR_DECLARED_INTERPRETATION' | 'INSUFFICIENT_OR_INCONCLUSIVE';

export type ReadinessFinding = {
  id: string;
  label: string;
  status: 'ESTABLISHED' | 'PARTIAL' | 'MISSING' | 'CONFLICT' | 'NOT_APPLICABLE';
  detail: string;
  evidence: string[];
};

export type ReadinessReport = {
  engine: 'TA14-EGRI';
  engineVersion: '1.0.0';
  state: ReadinessState;
  score: number;
  inspectionObject: string;
  proposition: string;
  supportedNow: string[];
  prohibitedInferences: string[];
  missingBeforeStrongerReliance: string[];
  nextAdmissibleSteps: string[];
  findings: ReadinessFinding[];
  eriEligible: boolean;
  generatedAt: string;
};

function has(text:string, pattern:RegExp){ return pattern.test(text); }
function snippets(text:string, pattern:RegExp){
  return text.split(/\n+/).map(x=>x.trim()).filter(Boolean).filter(x=>pattern.test(x)).slice(0,4);
}

export function examineEnvironmentalReadiness(input:{text:string; inspectionObject:string; proposition:string; recordClass:string}):ReadinessReport{
  const text=input.text.trim();
  const lower=text.toLowerCase();
  const findings:ReadinessFinding[]=[];
  const add=(id:string,label:string,status:ReadinessFinding['status'],detail:string,pattern?:RegExp)=>findings.push({id,label,status,detail,evidence:pattern?snippets(text,pattern):[]});

  const sourceIdentity=has(lower,/(record id|source|device|sensor|instrument|laboratory|lab report|technician|facility|building|site|manufacturer|serial)/i);
  add('source_identity','Source identity',sourceIdentity?'ESTABLISHED':'MISSING',sourceIdentity?'The submitted material contains source or record identity indicators.':'No reliable source or record identity was detected.',/(record id|source|device|sensor|instrument|laboratory|technician|facility|building|site|serial)/i);

  const timeBoundary=has(lower,/(\b20\d{2}[-\/]\d{1,2}[-\/]\d{1,2}\b|\b\d{1,2}:\d{2}\b|utc|\bet\b|period|timestamp|date|from .* to|through)/i);
  add('time_boundary','Time boundary',timeBoundary?'ESTABLISHED':'MISSING',timeBoundary?'A temporal boundary or timestamp signal is present.':'No sufficiently clear temporal boundary was detected.',/(20\d{2}|\d{1,2}:\d{2}|utc|\bet\b|period|timestamp|date|from|through)/i);

  const location=has(lower,/(room|zone|building|facility|site|address|location|floor|mechanical room|occupied zone|outdoor|indoor)/i);
  add('location','Location / spatial attribution',location?'ESTABLISHED':'MISSING',location?'The submitted material identifies a place, zone, or spatial context.':'No sufficiently clear location or spatial boundary was detected.',/(room|zone|building|facility|site|address|location|floor|outdoor|indoor)/i);

  const calibration=has(lower,/(calibrat|certificate|traceable|nist|verification date|sensor validation)/i);
  const calibrationConcern=has(lower,/(calibrat.{0,40}(expired|unknown|missing|partial|overdue|not current)|four of six)/i);
  add('calibration','Calibration / instrument standing',calibrationConcern?'PARTIAL':calibration?'ESTABLISHED':'MISSING',calibrationConcern?'Calibration evidence is present but contains a limitation or incomplete standing.':calibration?'Calibration or instrument-verification evidence is present.':'No calibration or instrument-standing evidence was detected.',/(calibrat|certificate|traceable|nist|sensor validation)/i);

  const gap=has(lower,/(missing interval|data gap|gap detected|interruption|offline|unavailable|dropout|loss of data|no data)/i);
  const continuity=has(lower,/(continuity|continuous|coverage|captured|sampling interval|sample interval|uptime|complete period)/i);
  add('continuity','Chronology / continuity',gap?'PARTIAL':continuity?'ESTABLISHED':'MISSING',gap?'The record declares a continuity interruption or missing interval.':continuity?'Continuity or coverage evidence is present.':'No continuity or coverage evidence was detected.',/(continuity|continuous|coverage|captured|sampling interval|uptime|missing interval|gap|offline)/i);

  const provenance=has(lower,/(chain of custody|custody|provenance|hash|sha-?256|signed|signature|version|revision|exported by|generated by)/i);
  add('provenance','Provenance / version identity',provenance?'ESTABLISHED':'MISSING',provenance?'Provenance, version, custody, signature, or integrity markers are present.':'No provenance, version, custody, or integrity marker was detected.',/(chain of custody|custody|provenance|hash|sha-?256|signed|signature|version|revision)/i);

  const threshold=has(lower,/(threshold|limit|guideline|standard|ashrae|epa|who|osha|permissible|acceptable|target|setpoint)/i);
  add('threshold_source','Threshold / reference source',threshold?'ESTABLISHED':'MISSING',threshold?'A threshold, limit, guideline, standard, or reference source is present.':'No declared threshold or reference source was detected.',/(threshold|limit|guideline|standard|ashrae|epa|who|osha|target|setpoint)/i);

  const objectLocalized=input.inspectionObject.trim().length>=20;
  add('object_localization','Inspection object localization',objectLocalized?'ESTABLISHED':'MISSING',objectLocalized?'A bounded inspection object has been declared.':'The inspection object remains insufficiently localized.');

  const propositionBound=input.proposition.trim().length>=20;
  add('proposition','Bounded proposition',propositionBound?'ESTABLISHED':'MISSING',propositionBound?'A bounded interpretation question has been declared.':'The proposition or interpretation question is too weakly bounded.');

  const conflict=has(lower,/(conflict|contradict|disagree|mismatch|inconsistent|different reading|sensor disagreement)/i);
  add('conflict','Conflicting evidence',conflict?'CONFLICT':'NOT_APPLICABLE',conflict?'The submitted material indicates conflicting or inconsistent evidence that must be resolved or bounded.':'No explicit conflict signal was detected.',/(conflict|contradict|disagree|mismatch|inconsistent)/i);

  const authority=has(lower,/(authorized by|authority|approved by|responsible party|owner authorization|engineer of record|licensed|permit|regulator)/i);
  add('authority','Authority / reliance boundary',authority?'ESTABLISHED':'MISSING',authority?'An authority or responsibility indicator is present.':'No authority or reliance boundary was detected.',/(authorized by|authority|approved by|responsible party|engineer of record|licensed|permit|regulator)/i);

  const material=findings.filter(f=>f.status!=='NOT_APPLICABLE');
  const established=material.filter(f=>f.status==='ESTABLISHED').length;
  const partial=material.filter(f=>f.status==='PARTIAL').length;
  const missing=material.filter(f=>f.status==='MISSING').length;
  const conflicts=material.filter(f=>f.status==='CONFLICT').length;
  const score=Math.max(0,Math.min(100,Math.round(((established + partial*.5)/(material.length||1))*100 - conflicts*8)));

  let state:ReadinessState='NOT_YET_GOVERNED';
  if(!text || text.length<40) state='INSUFFICIENT_OR_INCONCLUSIVE';
  else if(conflicts>0 || missing>=6) state='NOT_YET_GOVERNED';
  else if(missing>=3 || partial>=2) state='PARTIALLY_GOVERNABLE';
  else if(missing>=1 || partial>=1) state='READY_FOR_ADMISSIBILITY_REVIEW';
  else state='ADMISSIBLE_FOR_DECLARED_INTERPRETATION';

  const criticalIds=['source_identity','time_boundary','location','continuity','object_localization','proposition'];
  const eriEligible=criticalIds.every(id=>findings.find(f=>f.id===id)?.status==='ESTABLISHED') && !findings.some(f=>f.status==='CONFLICT') && state==='ADMISSIBLE_FOR_DECLARED_INTERPRETATION';

  const missingBeforeStrongerReliance=findings.filter(f=>['MISSING','PARTIAL','CONFLICT'].includes(f.status)).map(f=>`${f.label}: ${f.detail}`);
  const supportedNow=[
    sourceIdentity?'The package contains identifiable environmental source or record information.':'The package can be preserved as submitted material, but source identity is not yet established.',
    timeBoundary?'The material contains evidence tied to a declared or detectable time context.':'The material does not yet support unrestricted time-bounded interpretation.',
    location?'The material contains spatial or facility context relevant to bounded environmental interpretation.':'The material does not yet support unrestricted location-specific interpretation.',
  ];
  const prohibitedInferences=[
    'Do not convert environmental observations into a medical diagnosis or health outcome.',
    'Do not convert a threshold comparison into causal attribution without separate evidence.',
    'Do not treat missing or unparsed evidence as if it were inspected.',
    'Do not treat interpretation readiness as authority to execute a consequential intervention.',
  ];
  if(gap) prohibitedInferences.push('Do not make an unrestricted whole-period claim across declared continuity gaps.');
  if(conflict) prohibitedInferences.push('Do not select one conflicting source as authoritative without a declared resolution rule or bounded rationale.');

  const nextAdmissibleSteps=missingBeforeStrongerReliance.length?missingBeforeStrongerReliance.slice(0,6).map(x=>`Resolve ${x}`):['Submit the admitted evidence package to ERI for bounded interpretation.'];

  return {engine:'TA14-EGRI',engineVersion:'1.0.0',state,score,inspectionObject:input.inspectionObject.trim(),proposition:input.proposition.trim(),supportedNow,prohibitedInferences,missingBeforeStrongerReliance,nextAdmissibleSteps,findings,eriEligible,generatedAt:new Date().toISOString()};
}
